SEP = "<|endoftext|>"
LUNG = "Satul Nou este un sat din comuna Exemplu, județul Model, România. " * 6


def wikipedia_inchipuita(url, parametri=None, json_=True, pauza=0.0):
    if parametri.get("list") == "users":
        return {"query": {"users": [{"name": n, "groups": ["bot", "*"] if n == "Paznicul" else ["*", "user"]}
                                    for n in parametri["ususers"].split("|")]}}
    if parametri.get("list") == "recentchanges":
        if "rccontinue" not in parametri:
            return {"query": {"recentchanges": [
                {"title": "Satul Nou", "pageid": 1, "timestamp": "2026-10-14T10:00:00Z", "tags": ["visualeditor"],
                 "user": "Ana"},
                {"title": "Satul Vechi", "pageid": 6, "timestamp": "2026-10-14T10:30:00Z", "tags": [], "user": "SateBot"},
                {"title": "Satul Mic", "pageid": 7, "timestamp": "2026-10-14T10:40:00Z", "tags": [], "user": "Paznicul"},
                {"title": "Satul Mare", "pageid": 8, "timestamp": "2026-10-14T10:50:00Z", "tags": [], "user": "Ion",
                 "bot": True},
                {"title": "Recreat", "pageid": 2, "timestamp": "2026-10-14T11:00:00Z", "tags": ["mw-recreated"]},
            ]}, "continue": {"rccontinue": "x", "continue": "-||"}}
        return {"query": {"recentchanges": [
            {"title": "Tradus", "pageid": 3, "timestamp": "2026-10-15T10:00:00Z", "tags": ["contenttranslation"]},
            {"title": "Scurt", "pageid": 4, "timestamp": "2026-10-15T11:00:00Z", "tags": []},
            {"title": "Șters", "pageid": 5, "timestamp": "2026-10-15T12:00:00Z", "tags": []},
        ]}}
    pagini = {1: {"title": "Satul Nou", "extract": LUNG + "\n\nIstorie\n\nAre o biserică.\n\nReferințe\n\nCartea X, 2026.",
                  "revisions": [{"revid": 77, "timestamp": "2026-10-16T09:00:00Z"}]},
              4: {"title": "Scurt", "extract": "Prea scurt.", "revisions": [{"revid": 78}]},
              5: {"title": "Șters", "missing": True},
              **{k: {"title": f"Sat {k}", "extract": LUNG, "revisions": [{"revid": k}]} for k in (6, 7, 8)}}
    return {"query": {"pages": [pagini[parametri["pageids"]]]}}


def test_wikipedia_doar_articolele_cu_adevarat_noi():
    lista = en.articole_noi("ro", cere_=wikipedia_inchipuita)
    # fără recreate și traduceri; toate paginile
    assert [a["titlu"] for a in lista] == ["Satul Nou", "Satul Vechi", "Satul Mic", "Satul Mare", "Scurt", "Șters"]
    # robot: numele contului, grupul „bot”, semnul „bot” al creării
    assert [a["robot"] for a in lista] == [False, True, True, True, False, False]
    assert not en.ROBOT.search("Robertina") and en.ROBOT.search("Robot ABC") and en.ROBOT.search("XyzBot")
    texte = en.set_wikipedia("ro", None, cere_=wikipedia_inchipuita, spune=lambda *a, **k: None)
    texte = [x for x in texte if x["titlu"] == "Satul Nou"]
    assert len(texte) == 1 and texte[0]["revizie"] == 77 and texte[0]["robot"] is False and texte[0]["creator"] == "Ana" and texte[0]["licenta"] == "CC BY-SA 4.0"
    assert texte[0]["text"].endswith("Are o biserică.") and "Referințe" not in texte[0]["text"]
    assert texte[0]["adresa"] == "https://ro.wikipedia.org/?curid=1"


def test_filtrele_pentru_cod():
    arbore = [{"type": "blob", "path": "LICENSE", "size": 1000},
              {"type": "blob", "path": "src/app.py", "size": 3000},
              {"type": "blob", "path": "vendor/lib.py", "size": 3000},
              {"type": "blob", "path": "src/venv/x.py", "size": 3000},
              {"type": "blob", "path": "External/lib.py", "size": 3000},
              {"type": "blob", "path": "pkg/setup.py", "size": 3000},
              {"type": "blob", "path": "pkg/__init__.py", "size": 3000},
              {"type": "blob", "path": "docs/conf.py", "size": 3000},
              {"type": "blob", "path": "api/mesaje_pb2.py", "size": 3000},
              {"type": "blob", "path": "mic2.py", "size": 299},
              {"type": "blob", "path": "mic.py", "size": 50},
              {"type": "blob", "path": "mare.py", "size": 80_000},
              {"type": "blob", "path": "README.md", "size": 3000}]
    assert [f["path"] for f in en.fisiere_bune(arbore)] == ["src/app.py"]
    assert en.are_licenta(arbore) and not en.are_licenta(arbore[1:])
    assert en.are_licenta([{"type": "blob", "path": "LICENCE.txt"}])
    assert not en.are_licenta([{"type": "blob", "path": "docs/LICENSE"}])  # doar în rădăcina proiectului
    assert en.generat_automat("# Code generated by protoc. DO NOT EDIT.\nx = 1") and not en.generat_automat("x = 1\n")
    assert en.cod_vechi('"""\n Copyright (c) 2018 Intel Corporation\n"""\nx = 1') and en.cod_vechi("# Copyright 2019-2026 X")
    assert not en.cod_vechi("# Copyright (c) 2026 Ana\nx = 1") and not en.cod_vechi("x = 1  # fără notă")


def test_codul_doar_din_proiecte_noi_cu_licenta(monkeypatch):
    def github(url, parametri=None, json_=True, pauza=0.0):
        if "search/repositories" in url:
            if "license:mit" not in parametri["q"]:
                return {"items": []}
            return {"items": [
                {"full_name": "a/nou", "created_at": "2026-10-14T00:00:00Z", "license": {"spdx_id": "MIT"},
                 "default_branch": "main", "owner": {"login": "a"}, "fork": False},
                {"full_name": "b/vechi", "created_at": "2026-10-12T23:00:00Z", "license": {"spdx_id": "MIT"},
                 "default_branch": "main", "owner": {"login": "b"}, "fork": False},
                {"full_name": "c/fara", "created_at": "2026-10-15T00:00:00Z", "license": {"spdx_id": "MIT"},
                 "default_branch": "main", "owner": {"login": "c"}, "fork": False}]}
        if "git/trees" in url:
            fisiere = [{"type": "blob", "path": "main.py", "size": 500}]
            return {"sha": "abc", "tree": fisiere + ([{"type": "blob", "path": "LICENSE", "size": 1}] if "a/nou" in url else [])}
        return "def f(x):\n    return x * 2\n" * 20

    texte = en.set_cod(cere_=github, spune=lambda *a, **k: None)
    assert [(t["proiect"], t["fisier"], t["licenta"], t["arbore"]) for t in texte] == [("a/nou", "main.py", "MIT", "abc")]
    assert texte[0]["adresa"] == "https://raw.githubusercontent.com/a/nou/abc/main.py"


def test_setul_se_scrie_o_singura_data(tmp_path):
    s = en.scrie_set(tmp_path, "x", [{"text": "unu", "titlu": "A"}, {"text": "doi", "titlu": "B"}])
    assert (tmp_path / "x" / "validare.txt").read_text(encoding="utf-8") == f"unu\n{SEP}\ndoi\n{SEP}\n"
    assert s["texte"] == 2 and s["surse"] == [{"titlu": "A"}, {"titlu": "B"}] and len(s["sha256"]) == 64
    with pytest.raises(FileExistsError):
        en.scrie_set(tmp_path, "x", [{"text": "trei"}])


def test_examenul_pe_alte_validari_il_da_si_kronos(tmp_path, monkeypatch, capsys):
    pytest.importorskip("torch")
    monkeypatch.chdir(tmp_path)
    cale = config_mic(tmp_path, "antrenare_lunga_3", model=', cale_stare = "lucru/antrenare_lunga_3/gpt.pt"', spatiu="lot = [4]")
    assert antrenare_lunga.main(["--config", str(cale), "--ore", "1", "--pauza", "0", "--racire", "0", "--lungime", "20"]) == 0
    model_id = [f for f in fise(tmp_path) if f.get("model_salvat")][-1]["id"]
    nou = tmp_path / "nou.txt"
    nou.write_text(f"Pisica doarme pe covor.\n{SEP}\n" * 20, encoding="utf-8")
    seturi = tmp_path / "seturi.json"
    seturi.write_text(json.dumps({"wikipedia_ro_nou": str(nou)}), encoding="utf-8")
    assert ce.main(["--kronos", str(model_id), "--modele", "", "--validari", str(seturi), "--fire", "2"]) == 0
    raport = json.loads(next((tmp_path / "lucru" / "examen_neutru").glob("neutru_*.json")).read_text(encoding="utf-8"))
    kronos = raport["modele"][f"kronos_{model_id}"]
    assert kronos["examen"]["wikipedia_ro_nou"]["bpb"] > 0 and "din_memorie" not in kronos
    assert raport["validari"] == {"wikipedia_ro_nou": str(nou)}

    # pe tot setul, fiecare text singur, cu intervale
    assert ce.main(["--kronos", str(model_id), "--modele", "", "--validari", str(seturi), "--fire", "2", "--pe-text"]) == 0
    intreg = json.loads(next((tmp_path / "lucru" / "examen_neutru").glob("intreg_*.json")).read_text(encoding="utf-8"))
    k = intreg["modele"][f"kronos_{model_id}"]
    assert len(k["pe_text"]["wikipedia_ro_nou"]) == 20 and k["pe_text"]["wikipedia_ro_nou"][0]["inceput"] == "Pisica doarme pe covor."
    e = k["examen"]["wikipedia_ro_nou"]
    assert e["jos"] <= e["bpb"] <= e["sus"] and intreg["kronos_minus"] == {}
    with pytest.raises(SystemExit):
        ce.main(["--kronos", str(model_id), "--pe-text"])
